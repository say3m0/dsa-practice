class Solution {
public:
    int minInsertions(string s) {
        int res = 0;   // কতগুলো ইনসার্ট করতে হবে
        int bal = 0;   // আমার কতগুলো ')' দরকার তা ট্র্যাক করে (প্রতি '(' এর জন্য 2টি ')')

        for (char c : s) {
            if (c == '(') {
                // যদি আগের কোনো ഒറ്റ '(' বাকি থাকে এবং তার জন্য বিজোড় ব্যালেন্স থাকে
                if (bal % 2 != 0) {
                    res++;     // একটি ')' বাড়িয়ে জোড় বানিয়ে নিলাম
                    bal--;     // ব্যালেন্স ১ কমল
                }
                bal += 2;      // একটি '(' এর জন্য এখন আরও দুটি ')' লাগবে
            } 
            else { // c == ')'
                bal--;         // একটি ')' পাওয়া গেছে, তাই চাহিদা কমল
                if (bal < 0) { 
                    res++;     // একটি অতিরিক্ত ')' এর জন্য সামনে একটি '(' লাগবে
                    bal += 2;  // এবং ওই '(' এর জন্য বাকি থাকা দুটি ')' এর চাহিদা যোগ হলো
                }
            }
        }
        
        return res + bal; // লুপ শেষে যদি কোনো ')' এর চাহিদা (bal) বাকি থাকে, তা যোগ করে দিতে হবে
    }
};